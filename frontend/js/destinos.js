export function normalizarTexto(texto) {
  return String(texto || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

export function encontrarDestinoCatalogo(destinoTexto) {
  const norm = normalizarTexto(destinoTexto);
  if (!norm) return null;
  return (
    DESTINOS_BRASIL.find((d) =>
      d.chaves.some((chave) => norm.includes(normalizarTexto(chave)))
    ) || null
  );
}

export function listarReferenciasDoDestino(destinoTexto) {
  const destino = encontrarDestinoCatalogo(destinoTexto);
  if (!destino) return [];
  return [...destino.lugares, ...(destino.referencias || [])];
}

export function buscarReferenciaLocal(consulta, destinoTexto = '') {
  const q = normalizarTexto(consulta);
  if (!q) return null;

  const palavras = q.split(/\s+/).filter((p) => p.length >= 3 && !['dos', 'das', 'com', 'para'].includes(p));
  const alvo = encontrarDestinoCatalogo(destinoTexto);
  const todas = DESTINOS_BRASIL.flatMap((d) => [...d.lugares, ...(d.referencias || [])]);
  const listas = alvo ? [listarReferenciasDoDestino(destinoTexto), todas] : [todas];

  for (const lista of listas) {
    const exato = lista.find(
      (item) => normalizarTexto(item.nome) === q || normalizarTexto(item.local) === q
    );
    if (exato) {
      return { lat: exato.lat, lon: exato.lon, displayName: exato.local, nome: exato.nome };
    }

    const parcial = lista.find((item) => {
      const nNome = normalizarTexto(item.nome);
      const nLocal = normalizarTexto(item.local);
      const combinado = `${nNome} ${nLocal}`;
      if (q.length >= 4 && combinado.includes(q)) return true;
      if (nNome.length >= 5 && q.includes(nNome)) return true;
      if (palavras.length >= 2 && palavras.every((p) => combinado.includes(p))) return true;
      return false;
    });
    if (parcial) {
      return { lat: parcial.lat, lon: parcial.lon, displayName: parcial.local, nome: parcial.nome };
    }
  }

  const cidadeMatch = encontrarDestinoCatalogo(consulta);
  if (cidadeMatch && q.length <= cidadeMatch.cidade.length + 6) {
    return {
      lat: cidadeMatch.centro.lat,
      lon: cidadeMatch.centro.lon,
      displayName: cidadeMatch.cidade,
      nome: cidadeMatch.cidade,
    };
  }

  return null;
}

